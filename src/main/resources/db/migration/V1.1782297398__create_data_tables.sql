CREATE TABLE photo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url VARCHAR(512),
    caption TEXT,
    minio_key VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT,
    mood VARCHAR(50),
    created_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE settings (
    id BIGINT PRIMARY KEY,
    start_date DATE,
    couple_names VARCHAR(255)
);